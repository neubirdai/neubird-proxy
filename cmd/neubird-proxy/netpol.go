// cmdNetpol generates network egress rules from the config, so the hosts
// the pod may reach are exactly the configured upstreams. The proxy
// decides paths, methods and tools; this makes the network enforce the
// hosts underneath it, so one layer still holds if the other fails.
func cmdNetpol(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("netpol", flag.ContinueOnError)
	fs.SetOutput(stderr)
	var cf commonFlags
	cf.register(fs)
	format := fs.String("format", "cilium", "cilium (hostname rules, needs Cilium), kubernetes (IP rules from current DNS), or list (host:port lines for a firewall)")
	namespace := fs.String("namespace", "neubird", "namespace of the proxy pods")
	app := fs.String("app", "neubird-proxy", "value of the pods' app label")
	fs.Usage = func() {
		fmt.Fprintln(stderr, "usage: neubird-proxy netpol [-config path] [-format cilium|kubernetes|list] [-namespace ns]")
		fmt.Fprintln(stderr, "\nPrints egress rules allowing only the configured upstreams (and DNS). Secrets are not needed.")
		fs.PrintDefaults()
	}
	if fs.Parse(args) != nil {
		return 2
	}
	sec, err := loadSecrets(cf.envFile, true)
	if err != nil {
		fmt.Fprintln(stderr, "error:", err)
		return 1
	}
	cfg, _, err := loadConfig(cf.config, sec)
	if err != nil {
		for _, l := range splitErrors(err) {
			fmt.Fprintln(stderr, "error:", l)
		}
		return 1
	}
	dests := destinations(cfg)

	switch *format {
	case "list":
		for _, d := range dests {
			fmt.Fprintf(stdout, "%s:%s\n", d.host, d.port)
		}
	case "cilium":
		fmt.Fprint(stdout, ciliumPolicy(dests, *namespace, *app, cf.config))
	case "kubernetes":
		out, warns := kubernetesPolicy(dests, *namespace, *app, cf.config)
		for _, w := range warns {
			fmt.Fprintln(stderr, "warning:", w)
		}
		fmt.Fprint(stdout, out)
	default:
		fmt.Fprintf(stderr, "error: unknown -format %q\n", *format)
		return 2
	}
	return 0
}

type destination struct {
	host, port string
	ip         bool
	conns      []string
}

// destinations lists each distinct upstream host and port, with the
// connections that use it.
func destinations(cfg *config.Config) []destination {
	byKey := map[string]*destination{}
	for _, c := range cfg.Connections {
		u := c.UpstreamURL
		port := u.Port()
		if port == "" {
			port = map[string]string{"https": "443", "http": "80"}[u.Scheme]
		}
		host := strings.ToLower(u.Hostname())
		k := host + ":" + port
		if byKey[k] == nil {
			byKey[k] = &destination{host: host, port: port, ip: net.ParseIP(host) != nil}
		}
		byKey[k].conns = append(byKey[k].conns, c.Name)
	}
	var out []destination
	for _, d := range byKey {
		out = append(out, *d)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].host != out[j].host {
			return out[i].host < out[j].host
		}
		return out[i].port < out[j].port
	})
	return out
}

func ciliumPolicy(dests []destination, ns, app, configPath string) string {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by: neubird-proxy netpol -format cilium -config %s
# Egress for the proxy pods: DNS lookups of the upstream names only, then
# those hosts and ports only. Everything else is denied for these pods.
# Ingress is left to the NetworkPolicy in deploy/kubernetes.yaml.
apiVersion: cilium.io/v2
kind: CiliumNetworkPolicy
metadata:
  name: neubird-proxy-egress
  namespace: %s
spec:
  endpointSelector:
    matchLabels:
      app: %s
  egress:
    # The DNS proxy only answers for the upstream names, so the pod can't
    # even resolve anything else.
    - toEndpoints:
        - matchLabels:
            k8s:io.kubernetes.pod.namespace: kube-system
            k8s-app: kube-dns
      toPorts:
        - ports:
            - {port: "53", protocol: ANY}
          rules:
            dns:
`, configPath, ns, app)
	names := map[string]bool{}
	for _, d := range dests {
		if !d.ip && !names[d.host] {
			names[d.host] = true
			fmt.Fprintf(&b, "              - matchName: %q\n", d.host)
		}
	}
	if len(names) == 0 {
		b.WriteString("              - matchName: \"none.invalid\"   # every upstream is an IP address\n")
	}
	for _, d := range dests {
		fmt.Fprintf(&b, "    # %s\n", strings.Join(d.conns, ", "))
		if d.ip {
			fmt.Fprintf(&b, "    - toCIDR: [%q]\n", d.host+"/32")
		} else {
			fmt.Fprintf(&b, "    - toFQDNs:\n        - matchName: %q\n", d.host)
		}
		fmt.Fprintf(&b, "      toPorts:\n        - ports:\n            - {port: %q, protocol: TCP}\n", d.port)
	}
	return b.String()
}

// kubernetesPolicy resolves each upstream now and allows its current
// addresses: plain NetworkPolicy has no hostname rules. Right for a
// private APIM endpoint with stable addresses; brittle for anything behind
// a CDN or a changing load balancer, which is what the warning says.
func kubernetesPolicy(dests []destination, ns, app, configPath string) (string, []string) {
	var warns []string
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by: neubird-proxy netpol -format kubernetes -config %s
# on %s. NetworkPolicy can't match hostnames, so these are the addresses
# the upstreams resolved to then. Regenerate if they change, or use
# -format cilium where the cluster runs Cilium.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: neubird-proxy-egress
  namespace: %s
spec:
  podSelector:
    matchLabels:
      app: %s
  policyTypes: [Egress]
  egress:
    - ports: [{port: 53, protocol: UDP}, {port: 53, protocol: TCP}]
      to:
        - namespaceSelector: {}
          podSelector:
            matchLabels: {k8s-app: kube-dns}
`, configPath, time.Now().UTC().Format("2006-01-02 15:04 UTC"), ns, app)
	for _, d := range dests {
		addrs := []string{d.host}
		if !d.ip {
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			found, err := net.DefaultResolver.LookupHost(ctx, d.host)
			cancel()
			if err != nil {
				warns = append(warns, fmt.Sprintf("%s: %v; left out of the policy", d.host, err))
				fmt.Fprintf(&b, "    # %s (%s): could not resolve %s\n", strings.Join(d.conns, ", "), d.port, d.host)
				continue
			}
			addrs = found
			if len(found) > 1 {
				warns = append(warns, fmt.Sprintf("%s resolves to %d addresses; if it is behind a CDN or a changing load balancer, IP rules will break", d.host, len(found)))
			}
		}
		fmt.Fprintf(&b, "    # %s -> %s:%s\n    - ports: [{port: %s, protocol: TCP}]\n      to:\n", strings.Join(d.conns, ", "), d.host, d.port, d.port)
		sort.Strings(addrs)
		for _, a := range addrs {
			bits := "/32"
			if strings.Contains(a, ":") {
				bits = "/128"
			}
			fmt.Fprintf(&b, "        - ipBlock: {cidr: %q}\n", a+bits)
		}
	}
	return b.String(), warns
}
